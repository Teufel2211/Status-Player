-- 007 — Screenshot-Anhänge für /bug-Meldungen (StatusMod 1.4.2)
--
-- Ablauf: POST /api/bug-report legt pro Meldung einen 8-stelligen Upload-Code an
-- (nur als SHA-256-Hash gespeichert, 30 Minuten gültig). Über
-- /upload?c=CODE bzw. /api/bug-report/image?c=CODE hängen Spieler bis zu
-- 3 Bilder an. Bilder liegen im privaten Bucket "bug-images"; die Tabelle
-- bug_report_images verknüpft sie mit der Meldung (Cascade-Delete).

ALTER TABLE public.bug_reports
  ADD COLUMN IF NOT EXISTS upload_code_hash text,
  ADD COLUMN IF NOT EXISTS upload_code_expires_at timestamptz;

CREATE UNIQUE INDEX IF NOT EXISTS bug_reports_upload_code_hash_idx
  ON public.bug_reports (upload_code_hash)
  WHERE upload_code_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.bug_report_images (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id bigint NOT NULL REFERENCES public.bug_reports(id) ON DELETE CASCADE,
  storage_path text NOT NULL,
  mime text NOT NULL,
  size_bytes integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS bug_report_images_report_id_idx
  ON public.bug_report_images (report_id);

ALTER TABLE public.bug_report_images ENABLE ROW LEVEL SECURITY;

-- Privater Bucket (nur Service-Role; Zugriff ausschließlich über signierte URLs).
INSERT INTO storage.buckets (id, name, public)
VALUES ('bug-images', 'bug-images', false)
ON CONFLICT (id) DO NOTHING;
