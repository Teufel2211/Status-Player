-- 009 – Warnungen mit Ablauf und aktiver Warnstufe (StatusMod 1.4.2)
--
-- Jede Warnung ist ein eigener Datensatz mit Ablaufdatum. Der Badge-Level
-- ingame ist die Anzahl aktiver Warnungen (max. 3). Abgelaufene oder
-- zurueckgenommene Warnungen zaehlen nicht. Automatische Vergabe gibt es
-- nicht: der Owner fuegt Warnungen im Dashboard hinzu.
--
-- Server-Einstellungen (servers.config JSONB):
--   warn_default_days          = 14 (Standard-Gueltigkeit neuer Warnungen)
--   warn_auto_mute_suggestion  = false (Opt-in: Vorschlag ab 3 aktiven Warnungen)

CREATE TABLE IF NOT EXISTS public.player_warnings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id uuid NOT NULL REFERENCES public.servers(id) ON DELETE CASCADE,
  player_uuid text NOT NULL,
  reason text NOT NULL DEFAULT '',
  created_by uuid NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz NULL,
  revoked_by uuid NULL
);

CREATE INDEX IF NOT EXISTS player_warnings_active_idx
  ON public.player_warnings (server_id, player_uuid, expires_at)
  WHERE revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS player_warnings_server_idx
  ON public.player_warnings (server_id, created_at DESC);

ALTER TABLE public.player_warnings ENABLE ROW LEVEL SECURITY;

